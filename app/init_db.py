import os
import sys
sys.path.append(os.path.dirname(os.path.abspath(__file__)))

from models import db, User, Post, Message
from main import app

def init_db():
    with app.app_context():
        db.drop_all()
        db.create_all()
        
        emma = User(
            username='emma',
            bio=os.getenv('FLAG'),
            is_bot=True,
            is_readonly=True
        )
        emma.set_password('emma123')

        demo = User(username='demo')
        demo.set_password('demo123')
        
        db.session.add_all([emma, demo])
        db.session.commit()

        posts = [
            Post(
                author_id=emma.id,
                title='Что делать, если грустно',
                content='Грусть — это естественная эмоция, и важно позволить себе её прожить. Когда тебе грустно, попробуй начать с малого: выпей тёплый чай, закутайся в плед, посмотри любимый фильм. Иногда помогает написать о своих чувствах — просто выплеснуть всё на бумагу, не думая о красоте слога. Прогулка, даже короткая, тоже может изменить состояние: свежий воздух и смена обстановки творят чудеса. А если есть силы, позвони близкому человеку — иногда просто звук родного голоса согревает лучше любых слов. Помни: грусть не навсегда, она придёт и уйдёт, как волна. Главное — не ругать себя за неё.',
                is_private=False
            ),
            Post(
                author_id=emma.id,
                title='Что делать, если тревожно',
                content='Тревога часто приходит из-за неопределённости, когда будущее кажется туманным. В такие моменты хорошо помогают простые техники заземления. Попробуй сделать глубокий вдох на 4 счета, задержать дыхание на 7 и медленно выдохнуть на 8 — повтори несколько раз. Ещё можно оглядеться вокруг и мысленно отметить 5 вещей, которые ты видишь, 4 — которые можешь потрогать, 3 — слышишь, 2 — чувствуешь запах и 1 — можешь попробовать на вкус. Если тревога не отпускает, попробуй выписать всё, что тебя беспокоит — часто список оказывается не таким страшным, как казалось в голове. И помни: тревога — это волна, она нарастает и отступает, нужно просто дать ей время.',
                is_private=False
            ),
            Post(
                author_id=emma.id,
                title='Что делать, если нет сил',
                content='Когда сил нет совсем, важно не заставлять себя что-то делать, а наоборот — разрешить себе остановиться. Начни с самого простого: выпей стакан воды, открой окно, посиди в тишине пять минут. Тёплая еда, особенно суп или каша, даёт ощущение заботы и медленно возвращает энергию. Если есть возможность, выйди на свет — даже в пасмурный день дневной свет помогает организму проснуться. Составь список из трёх самых простых дел на день (например, умыться, поесть, ответить на одно сообщение) и радуйся каждому выполненному. И самое главное — позволь другим помогать тебе. Просить о помощи — это нормально, это не слабость.',
                is_private=False
            )
        ]
        
        db.session.add_all(posts)
        db.session.commit()

        welcome_msg = Message(
            user_id=demo.id,
            content='Приветствую, demo! Добро пожаловать в MoodSpace. Ты всегда можешь обратиться ко мне за помощью ♥',
            from_bot=True
        )
        db.session.add(welcome_msg)
        db.session.commit()
        
        print("База данных инициализирована")
        print(f"Флаг задан!")

if __name__ == '__main__':
    init_db()
